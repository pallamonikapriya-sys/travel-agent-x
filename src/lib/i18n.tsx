const DICTS: Record<LangCode, Dict> = { en, hi, es, fr };

const HTML_LANG: Record<LangCode, string> = { en: "en", hi: "hi", es: "es", fr: "fr" };

type Translate = (key: TranslationKey | string, vars?: Record<string, string | number>) => string;

type I18nValue = { lang: LangCode; setLang: (l: LangCode) => void; t: Translate };

function translate(lang: LangCode, key: string, vars?: Record<string, string | number>) {
  const raw = DICTS[lang][key] ?? (en as Dict)[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.split(`{${k}}`).join(String(v)), raw);
}

const I18nContext = createContext<I18nValue>({
  lang: "en",
  setLang: () => {},
  t: (key, vars) => translate("en", String(key), vars),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("tripmind-lang") as LangCode | null;
    if (saved && saved in DICTS) setLangState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = HTML_LANG[lang];
  }, [lang]);

  const setLang = (l: LangCode) => {
    setLangState(l);
    window.localStorage.setItem("tripmind-lang", l);
  };

  const t: Translate = (key, vars) => translate(lang, String(key), vars);

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
